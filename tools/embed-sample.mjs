// Packs skills/ggp-guide-builder/examples/mini-guide and embeds it in the Game Guide widget as the built-in sample.
import { writeFileSync } from "node:fs";
import { packDir } from "../skills/ggp-guide-builder/scripts/lib/pack.mjs";

const { bytes, report } = packDir(new URL("../skills/ggp-guide-builder/examples/mini-guide", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
if (!bytes || !report.ok) { console.error(report.errors); process.exit(1); }
writeFileSync(new URL("../widgets/game-guide/js/sample.js", import.meta.url), `// Generated by tools/embed-sample.mjs. Do not edit.\nwindow.SAMPLE_GGP_B64 = "${Buffer.from(bytes).toString("base64")}";\n`);
console.log("embedded sample,", bytes.length, "bytes");
